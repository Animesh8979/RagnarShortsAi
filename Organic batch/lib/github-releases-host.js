/**
 * lib/github-releases-host.js — Phase 6.2
 *
 * Replaces cloudflared/Litterbox as the IG public-URL host. Uses GitHub
 * Releases as the file store:
 *   - 2GB / file
 *   - Unmetered bandwidth, permanent URL
 *   - Free, no card-on-file (only needs a GitHub PAT or `gh auth login`)
 *   - HTTPS origin owned by github.com → not flagged by Meta as anonymous
 *
 * The actual URL Meta receives:
 *   https://github.com/{OWNER}/{REPO}/releases/download/v{ts}/render.mp4
 *
 * Required: `gh` CLI installed + authenticated, OR
 *   `GITHUB_RELEASES_OWNER`, `GITHUB_RELEASES_REPO`, `GITHUB_RELEASES_TOKEN`
 *   env vars (a fine-grained PAT with `contents:write` on the target repo).
 *
 * Token-based path (no gh CLI dependency) is preferred for CI / self-
 * hosted runners. Falls back to `gh release create` when token absent.
 *
 * IMPORTANT: This module assumes a DEDICATED public repo for hosting
 * (set via env GITHUB_RELEASES_REPO, default `<owner>/ragnar-media-host`).
 * Do NOT use the suppression-recovery / god-tier source repo — putting
 * MP4s on the actual code repo bloats clones and tangles release notes.
 */

'use strict';

require('./env-d-drive-only');

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const fetch = require('node-fetch');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');

function nowTagName() {
  return 'v' + Math.floor(Date.now() / 1000);
}

function defaultRepo() {
  return process.env.GITHUB_RELEASES_REPO || process.env.GH_HOST_REPO || null;
}

function defaultOwner() {
  return process.env.GITHUB_RELEASES_OWNER || (process.env.GITHUB_RELEASES_REPO || '').split('/')[0] || null;
}

function authHeader() {
  const token = process.env.GITHUB_RELEASES_TOKEN || process.env.GITHUB_TOKEN || process.env.GH_TOKEN;
  return token ? { Authorization: `Bearer ${token}` } : null;
}

/**
 * uploadToReleases(filePath, opts) → { ok, url, releaseUrl, tag, assetId } | { ok:false, reason }
 *
 * @param {string} filePath              local file (MP4 typically)
 * @param {object} [opts]
 * @param {string} [opts.repo]           "owner/repo" target — defaults to GITHUB_RELEASES_REPO
 * @param {string} [opts.tag]            release tag; default v{epoch_seconds}
 * @param {string} [opts.title]          release title; default filename
 * @param {string} [opts.notes]          release body; default "auto"
 * @param {boolean}[opts.prerelease=true] mark as prerelease to keep main release-list clean
 */
async function uploadToReleases(filePath, opts = {}) {
  if (!filePath || !fs.existsSync(filePath)) return { ok: false, reason: 'file_missing:' + filePath };
  const stat = fs.statSync(filePath);
  if (stat.size > 2 * 1024 * 1024 * 1024) return { ok: false, reason: 'file_over_2GB' };
  const repo = opts.repo || defaultRepo();
  if (!repo) return { ok: false, reason: 'no_GITHUB_RELEASES_REPO_configured' };
  const [owner, repoName] = String(repo).split('/');
  if (!owner || !repoName) return { ok: false, reason: 'GITHUB_RELEASES_REPO_must_be_owner/repo' };

  const tag = opts.tag || nowTagName();
  const title = opts.title || path.basename(filePath);
  const notes = opts.notes || 'auto-generated by Ragnar pipeline';
  const prerelease = opts.prerelease !== false;

  const auth = authHeader();
  if (auth) {
    return uploadViaApi({ filePath, owner, repoName, tag, title, notes, prerelease, auth });
  }
  return uploadViaGhCli({ filePath, repo, tag, title, notes, prerelease });
}

async function uploadViaApi({ filePath, owner, repoName, tag, title, notes, prerelease, auth }) {
  // 1. Create the release.
  let release;
  try {
    const r = await fetch(`https://api.github.com/repos/${owner}/${repoName}/releases`, {
      method: 'POST',
      headers: { ...auth, 'Content-Type': 'application/json', 'Accept': 'application/vnd.github+json' },
      body: JSON.stringify({ tag_name: tag, name: title, body: notes, prerelease, draft: false }),
      signal: AbortSignal.timeout(30_000),
    });
    if (!r.ok) {
      const text = await r.text().catch(() => '');
      return { ok: false, reason: `release_create_http_${r.status}: ${text.slice(0, 200)}` };
    }
    release = await r.json();
  } catch (e) {
    return { ok: false, reason: `release_create_threw: ${(e && e.message || e).slice(0, 200)}` };
  }
  if (!release || !release.upload_url || !release.id) return { ok: false, reason: 'release_no_upload_url' };

  // 2. Upload the asset. The upload_url contains a {?name,label} template.
  const fileName = path.basename(filePath);
  const uploadUrl = release.upload_url.replace(/\{[^}]+\}$/, '') + `?name=${encodeURIComponent(fileName)}`;
  const fileStream = fs.createReadStream(filePath);
  let asset;
  try {
    const r = await fetch(uploadUrl, {
      method: 'POST',
      headers: { ...auth, 'Content-Type': 'application/octet-stream', 'Content-Length': String(fs.statSync(filePath).size), 'Accept': 'application/vnd.github+json' },
      body: fileStream,
      signal: AbortSignal.timeout(15 * 60 * 1000),  // up to 15 min for large MP4s
    });
    if (!r.ok) {
      const text = await r.text().catch(() => '');
      return { ok: false, reason: `asset_upload_http_${r.status}: ${text.slice(0, 200)}` };
    }
    asset = await r.json();
  } catch (e) {
    return { ok: false, reason: `asset_upload_threw: ${(e && e.message || e).slice(0, 200)}` };
  }
  return {
    ok: true,
    url: asset.browser_download_url,
    releaseUrl: release.html_url,
    tag,
    assetId: asset.id,
    releaseId: release.id,
  };
}

function uploadViaGhCli({ filePath, repo, tag, title, notes, prerelease }) {
  const args = ['release', 'create', tag, filePath, '--repo', repo, '--title', title, '--notes', notes];
  if (prerelease) args.push('--prerelease');
  const r = spawnSync('gh', args, { encoding: 'utf8', timeout: 15 * 60 * 1000 });
  if (r.status !== 0) {
    return { ok: false, reason: `gh_cli_failed_exit_${r.status}: ${(r.stderr || '').slice(-200)}` };
  }
  // gh prints the release URL to stdout. Convert to the download URL:
  const fileName = path.basename(filePath);
  const url = `https://github.com/${repo}/releases/download/${tag}/${encodeURIComponent(fileName)}`;
  return { ok: true, url, tag, repo, stdout: (r.stdout || '').trim() };
}

module.exports = { uploadToReleases };

if (require.main === module) {
  const args = process.argv.slice(2);
  if (args[0] === '--help' || !args[0]) {
    console.log('Usage: node lib/github-releases-host.js <file.mp4> [--repo owner/repo] [--tag v123]');
    process.exit(2);
  }
  const filePath = args[0];
  const repoIdx = args.indexOf('--repo');
  const tagIdx = args.indexOf('--tag');
  uploadToReleases(filePath, {
    repo: repoIdx >= 0 ? args[repoIdx + 1] : undefined,
    tag: tagIdx >= 0 ? args[tagIdx + 1] : undefined,
  }).then((r) => { console.log(JSON.stringify(r, null, 2)); process.exit(r.ok ? 0 : 1); });
}
